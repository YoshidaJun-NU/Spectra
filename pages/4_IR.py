class MockUploadedFile:
    """st.file_uploaderの挙動を模倣するクラス"""
    def __init__(self, name, content_str):
        self.name = name
        self.content_bytes = content_str.encode('utf-8')

    def getvalue(self):
        return self.content_bytes

def load_data(uploaded_files):
    data_list = []
    for f in uploaded_files:
        try:
            content = f.getvalue()
            for enc in ['utf-8', 'cp932', 'shift_jis', 'latin1']:
                try: 
                    text = content.decode(enc)
                    break
                except: 
                    continue
            
            lines = text.splitlines()
            x_unit, y_unit = "Wavenumber (cm⁻¹)", "Transmittance (%)"
            use_skip = 0
            
            # ヘッダー解析
            for i, line in enumerate(lines):
                if 'XUNITS' in line:
                    val = line.split(',')[-1].strip() or line.split('\t')[-1].strip()
                    if val: x_unit = val
                if 'YUNITS' in line:
                    val = line.split(',')[-1].strip() or line.split('\t')[-1].strip()
                    if val: y_unit = val
                if 'XYDATA' in line:
                    use_skip = i + 1
                    break
            
            # CSV読み込み
            sep = ',' if f.name.lower().endswith('.csv') else None
            df = pd.read_csv(io.StringIO(text), sep=sep, skiprows=use_skip, header=None, engine='python')
            df = df.apply(pd.to_numeric, errors='coerce').dropna()
            
            if df.shape[1] >= 2:
                data_list.append({
                    'label': f.name.rsplit('.', 1)[0],
                    'x': df.iloc[:, 0].values,
                    'y': df.iloc[:, 1].values,
                    'x_unit': x_unit,
                    'y_unit': y_unit
                })
        except Exception as e:
            st.error(f"{f.name} の読み込み失敗: {e}")
    return data_list

